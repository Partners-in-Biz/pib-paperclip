#!/usr/bin/env node
/**
 * Embeds the template pack (templates/) into src/pack/data.generated.ts, so the
 * worker, the page and the tests all read the same data without a file loader.
 *
 *   node scripts/embed-templates.mjs           write src/pack/data.generated.ts
 *   node scripts/embed-templates.mjs --check   exit 1 when the committed file is out of date
 *
 * `pnpm build` runs it first; a test also fails when the committed file is stale.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(root, "src", "pack", "data.generated.ts");

/** The generated module's text for the current templates/ folder. */
export function renderGenerated(base = root) {
  const dir = join(base, "templates");
  const manifest = JSON.parse(readFileSync(join(dir, "manifest.json"), "utf8"));
  const starter = JSON.parse(readFileSync(join(dir, "memory", "starter-pack.json"), "utf8"));
  const files = {};
  const blocks = {};
  for (const name of readdirSync(join(dir, "agents")).sort()) {
    if (!name.endsWith(".md")) continue;
    const text = readFileSync(join(dir, "agents", name), "utf8");
    if (name.startsWith("_")) blocks[name.slice(1, -3)] = text;
    else files[name.slice(0, -3)] = text;
  }
  const json = (value) => JSON.stringify(value, null, 2);
  return [
    "// GENERATED by scripts/embed-templates.mjs from templates/. Do not edit: edit templates/ and run `node scripts/embed-templates.mjs`.",
    "",
    `export const PACK_MANIFEST_JSON: unknown = ${json(manifest)};`,
    "",
    `export const PACK_SHARED_BLOCKS: Record<string, string> = ${json(blocks)};`,
    "",
    `export const PACK_AGENT_FILES: Record<string, string> = ${json(files)};`,
    "",
    `export const STARTER_PACK_JSON: unknown = ${json(starter)};`,
    "",
  ].join("\n");
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const text = renderGenerated();
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(OUT, "utf8");
    } catch {
      current = "";
    }
    if (current !== text) {
      console.error("src/pack/data.generated.ts is out of date. Run: node scripts/embed-templates.mjs");
      process.exit(1);
    }
    console.log("template pack data is up to date");
  } else {
    writeFileSync(OUT, text);
    console.log(`wrote ${OUT}`);
  }
}
